const fs = require('fs');
const path = require('path');
const { config, config_mod, compute_auto_offset } = require('./lib/utils');

function parse_args(argv) {
  const options = {
    auto: false,
    offset: null,
    base: null,
    alias: null,
    shared_db: false,
    dir: process.cwd(),
    force: false,
    docker: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];

    if (arg === '--auto') {
      options.auto = true;
      continue;
    }

    if (arg === '--docker') {
      options.docker = true;
      continue;
    }

    if (arg === '--force') {
      options.force = true;
      continue;
    }

    if (arg === '--shared-db') {
      options.shared_db = true;
      continue;
    }

    if (arg === '--offset') {
      options.offset = argv[i + 1];
      i += 1;
      continue;
    }

    if (arg.startsWith('--offset=')) {
      options.offset = arg.split('=')[1];
      continue;
    }

    if (arg === '--base') {
      options.base = argv[i + 1];
      i += 1;
      continue;
    }

    if (arg.startsWith('--base=')) {
      options.base = arg.split('=')[1];
      continue;
    }

    if (arg === '--alias') {
      options.alias = argv[i + 1];
      i += 1;
      continue;
    }

    if (arg.startsWith('--alias=')) {
      options.alias = arg.split('=')[1];
      continue;
    }

    if (arg === '--dir') {
      options.dir = argv[i + 1];
      i += 1;
      continue;
    }

    if (arg.startsWith('--dir=')) {
      options.dir = arg.split('=')[1];
      continue;
    }

    console.error(`Unknown argument: ${arg}`);
    return null;
  }

  if (!options.auto && options.offset === null && options.base === null) {
    options.auto = true;
  }

  return options;
}

function parse_integer(value, label) {
  const parsed = Number.parseInt(value, 10);
  if (Number.isNaN(parsed)) {
    throw new Error(`${label} must be an integer`);
  }
  return parsed;
}

/**
 * Resolve env.localDefaults templates and return env lines.
 * Templates: {name}, {alias}, {offset}, {path}, {domain}, {appPort}
 */
function resolve_local_defaults(worktree_name, offset, resolved_dir, app_port) {
  const local_defaults = config && config.env && config.env.localDefaults;
  if (!local_defaults) return [];

  const alias = worktree_name.replace(/[^a-zA-Z0-9-]/g, '-').toLowerCase();
  const domain_template = config && config.docker && config.docker.proxy && config.docker.proxy.domainTemplate;
  const domain = domain_template
    ? domain_template.replace(/\{alias\}/g, alias)
    : `${alias}.localhost`;

  const replacements = {
    '{name}': worktree_name,
    '{alias}': alias,
    '{offset}': String(offset),
    '{path}': resolved_dir,
    '{domain}': domain,
    '{appPort}': String(app_port),
  };

  const lines = [];
  for (const [key, template] of Object.entries(local_defaults)) {
    let value = template;
    for (const [token, replacement] of Object.entries(replacements)) {
      value = value.split(token).join(replacement);
    }
    lines.push(`${key}=${value}`);
  }
  return lines;
}

function format_env_lines(options) {
  const resolved_dir = path.resolve(options.dir);
  const worktree_name = path.basename(resolved_dir);

  const offset_value =
    options.offset !== null
      ? parse_integer(options.offset, 'WORKTREE_PORT_OFFSET')
      : options.base === null
        ? compute_auto_offset(options.dir)
        : null;

  if (options.docker) {
    const db_name = config
      ? (options.shared_db ? (config.database.defaultDb || 'db') : (options.alias ? config_mod.db_name(config, options.alias) : (config.database.defaultDb || 'db')))
      : (options.shared_db ? 'db' : (options.alias ? `db_${options.alias.replace(/[^a-zA-Z0-9_]/g, '_')}` : 'db'));

    const VAR_PATH = config ? config_mod.env_var(config, 'projectPath') : 'PROJECT_PATH';
    const VAR_NAME = config ? config_mod.worktree_var(config, 'name') : 'WORKTREE_NAME';
    const VAR_ALIAS = config ? config_mod.worktree_var(config, 'alias') : 'WORKTREE_ALIAS';
    const container_workdir = config ? config.docker.generate.containerWorkdir : '/app';

    const lines = [
      '# Generated by create-worktree-env.js (docker)',
      `${VAR_PATH}=${container_workdir}`,
      `${VAR_NAME}=${worktree_name}`,
    ];
    if (options.alias) {
      lines.push(`${VAR_ALIAS}=${options.alias}`);
    }
    const domain = config
      ? (options.alias ? config_mod.domain_for(config, options.alias) : 'localhost')
      : (options.alias ? `${options.alias.replace(/[^a-zA-Z0-9-]/g, '-').toLowerCase()}.localhost` : 'localhost');

    // Database env vars — only when config provides database settings
    if (config && config.database) {
      const VAR_DB = config_mod.env_var(config, 'dbConnection');
      if (VAR_DB) {
        const db_host = config.database.containerHost || 'localhost';
        const db_port = config.database.port || 27017;
        const db_type = config.database.type || 'mongodb';
        if (db_type === 'mongodb') {
          const replica_set = config.database.replicaSet;
          lines.push(`${VAR_DB}=mongodb://${db_host}:${db_port}/${db_name}`);
          if (replica_set) {
            const VAR_REPLICA = config_mod.env_var(config, 'dbReplicaSet');
            if (VAR_REPLICA) lines.push(`${VAR_REPLICA}=${replica_set}`);
          }
        } else if (db_type === 'postgresql') {
          lines.push(`${VAR_DB}=postgresql://postgres@${db_host}:${db_port}/${db_name}`);
        } else {
          lines.push(`${VAR_DB}=${db_type}://${db_host}:${db_port}/${db_name}`);
        }
      }
    }

    // Redis env vars — only when config provides redis settings
    if (config && config.redis) {
      const VAR_REDIS_HOST = config_mod.env_var(config, 'redisHost');
      const VAR_REDIS_PORT = config_mod.env_var(config, 'redisPort');
      if (VAR_REDIS_HOST) lines.push(`${VAR_REDIS_HOST}=${config.redis.containerHost || 'redis'}`);
      if (VAR_REDIS_PORT) lines.push(`${VAR_REDIS_PORT}=${config.redis.port || 6379}`);
    }

    // App URL and domain env vars
    const VAR_LOCAL_IP = config ? config_mod.env_var(config, 'localIp') : null;
    const VAR_APP_URL = config ? config_mod.env_var(config, 'appUrl') : null;
    if (VAR_LOCAL_IP) lines.push(`${VAR_LOCAL_IP}=${domain}`);
    if (VAR_APP_URL) lines.push(`${VAR_APP_URL}=http://${domain}/`);

    lines.push('');
    return lines;
  }

  const VAR_PATH = config ? config_mod.env_var(config, 'projectPath') : 'PROJECT_PATH';
  const VAR_NAME = config ? config_mod.worktree_var(config, 'name') : 'WORKTREE_NAME';

  if (options.base !== null) {
    const VAR_PORT_BASE = config ? config_mod.worktree_var(config, 'portBase') : 'WORKTREE_PORT_BASE';
    const base = parse_integer(options.base, VAR_PORT_BASE);
    const lines = [
      '# Generated by scripts/worktree/create-worktree-env.js',
      `${VAR_PATH}=${resolved_dir}`,
      `${VAR_NAME}=${worktree_name}`,
      `${VAR_PORT_BASE}=${base}`,
    ];
    const primary_port = config && config.services.primary && config.services.ports[config.services.primary]
      ? config.services.ports[config.services.primary] + (base - 3000)
      : base + 1;
    lines.push(...resolve_local_defaults(worktree_name, base - 3000, resolved_dir, primary_port));
    lines.push('');
    return lines;
  }

  const VAR_PORT_OFFSET = config ? config_mod.worktree_var(config, 'portOffset') : 'WORKTREE_PORT_OFFSET';
  const lines = [
    '# Generated by scripts/worktree/create-worktree-env.js',
    `${VAR_PATH}=${resolved_dir}`,
    `${VAR_NAME}=${worktree_name}`,
    `${VAR_PORT_OFFSET}=${offset_value}`,
  ];
  const primary_port = config && config.services.primary && config.services.ports[config.services.primary]
    ? config.services.ports[config.services.primary] + offset_value
    : 3001 + offset_value;
  lines.push(...resolve_local_defaults(worktree_name, offset_value, resolved_dir, primary_port));
  lines.push('');
  return lines;
}

function main() {
  const options = parse_args(process.argv.slice(2));
  if (!options) {
    process.exit(1);
  }

  const target_dir = path.resolve(options.dir);
  if (!fs.existsSync(target_dir)) {
    console.error(`Directory does not exist: ${target_dir}`);
    process.exit(1);
  }

  if (!options.auto && options.offset === null && options.base === null) {
    console.error('Provide --auto, --offset, or --base.');
    process.exit(1);
  }

  const env_filename = config ? config.env.filename : '.env.worktree';
  const env_path = path.join(target_dir, env_filename);
  if (fs.existsSync(env_path) && !options.force) {
    console.error(`${env_filename} already exists at ${env_path}. Use --force to overwrite.`);
    process.exit(1);
  }

  const lines = format_env_lines(options);
  fs.writeFileSync(env_path, `${lines.join('\n')}\n`, 'utf8');
  console.log(`Wrote ${env_path}`);
}

main();
